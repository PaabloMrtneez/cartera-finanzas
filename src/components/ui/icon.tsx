/** El nombre de un color de la paleta de categorías; el código si no es de ella. */
export function nombreColor(color: string): string {
  return NOMBRE_COLOR[color.toLowerCase()] ?? color;
}

export function isIconName(value: string): value is IconName {
  return value in ICONS;
}

export function Icon({
  name,
  size = 20,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  // Una categoría creada con una versión anterior podría tener un icono que ya
  // no exista: mejor una interrogación que una pantalla rota.
  const Component = (isIconName(name) ? ICONS[name] : ICONS["circle-help"]) as LucideIcon;
  return <Component size={size} className={className} aria-hidden />;
}
